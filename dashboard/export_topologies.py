"""Export all 6 FaultFerence network topologies into static `dashboard/static/topologies.js`.

Allows `Inspector Switch` (`dashboard/static/`) to run 100% client-side on GitHub Pages (`github.io`)
with zero Python backend.
"""

import json
import os
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from dashboard import game  # noqa: E402


def build_bundle() -> dict:
    bundle = {}
    for name in game.TOPOLOGIES:
        net = game.get_network(name)
        edges = []
        for u, v in sorted(net.G.edges()):
            a, b = (u, v) if u < v else (v, u)
            edges.append([
                int(a),
                int(b),
                round(float(net.edge_capacities[(u, v)]), 1),
                round(float(net.edge_loads[(u, v)]), 4),
            ])
        cfg = net.safety
        bundle[name] = {
            "name": net.name,
            "switches": [int(x) for x in net.switch_nodes],
            "racks": [int(x) for x in net.rack_nodes],
            "names": {str(k): game._name(net, k) for k in net.switch_nodes},
            "edges": edges,
            "articulation": [int(x) for x in sorted(net._articulation_points)],
            "dlb": bool(net.dlb_routing),
            "safety": {
                "min_bw": float(cfg.min_bandwidth_ratio),
                "drain_ban": [int(x) for x in sorted(cfg.drain_banned_nodes)],
                "reset_ban": [int(x) for x in sorted(cfg.reset_banned_nodes)],
                "probe_ban": [int(x) for x in sorted(cfg.probe_banned_nodes)],
                "mirror_filt": [int(x) for x in sorted(cfg.mirror_filtered_nodes)],
                "mirror_raw": [int(x) for x in sorted(cfg.mirror_unfiltered_only_nodes)],
                "mirror_ban": [int(x) for x in sorted(cfg.mirror_banned_nodes)],
                "blackbox": [int(x) for x in sorted(cfg.external_blackbox_nodes)],
                "max_raw_load": float(cfg.max_unfiltered_mirror_load),
                "en_weight": bool(cfg.enable_subtle_weight_shifts),
                "en_split": bool(cfg.enable_group_splits),
                "en_drain": bool(cfg.enable_flow_link_drains),
                "en_mirror": bool(cfg.enable_packet_mirror),
                "en_reset": bool(cfg.enable_component_reset),
            },
        }
    return bundle


def main() -> None:
    bundle = build_bundle()
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "static", "topologies.js")
    payload = json.dumps(bundle, separators=(",", ":"))
    js = (
        "// Auto-generated by dashboard/export_topologies.py — static topology bundle for GitHub Pages.\n"
        '"use strict";\n'
        f"window.TOPOLOGY_DATA = {payload};\n"
    )
    with open(out_path, "w", encoding="utf-8") as fp:
        fp.write(js)
    print(f"Wrote {out_path} ({len(js)} bytes, {len(bundle)} topologies)")


if __name__ == "__main__":
    main()
